/* global console */
// Copies the engine stylesheet into a TypeScript module so published websites can serve it without reading files at runtime
// (serverless functions do not reliably ship arbitrary files). Run automatically before dev/build; `pnpm test` fails if it is stale.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const css = readFileSync(resolve(root, '../../packages/engine/src/styles/engine.css'), 'utf8');
const hash = createHash('sha256').update(css).digest('hex').slice(0, 12);
const out = resolve(root, 'lib/published/engine-css.generated.ts');
mkdirSync(dirname(out), { recursive: true });
const body = `// GENERATED by scripts/gen-engine-css.mjs from packages/engine/src/styles/engine.css. Do not edit.\nexport const ENGINE_CSS_HASH = ${JSON.stringify(hash)};\nexport const ENGINE_CSS = ${JSON.stringify(css)};\n`;
writeFileSync(out, body);
console.log(`engine css → ${hash}`);
